#!/bin/bash
# Первые N секунд видео без звука, с перекодированием (точно по кадрам).
# Использование: cut.sh <вход> <выход> <секунды>
export PATH="$HOME/.local/bin:$PATH"
[[ $# -eq 3 ]] || { echo "Использование: $0 <вход> <выход> <секунды>" >&2; exit 2; }
[[ -f $1 ]] || { echo "Нет файла: $1" >&2; exit 2; }
[[ $3 =~ ^[0-9]+(\.[0-9]+)?$ ]] && awk "BEGIN{exit !($3>0)}" || { echo "Секунды должны быть числом > 0: $3" >&2; exit 2; }
ffmpeg -v error -y -i "$1" -t "$3" -an -c:v libx264 -crf 18 -preset fast -pix_fmt yuv420p "$2" || exit 1
echo "$2"
